"""Built-in archetype seed map and mana-base templates.

The tournament-derived corpus is thin and missing common shells (no Burn, no
Tron, no Yawgmoth, etc.). When the user's brief names one of these archetypes,
we inject a canonical seed list of anchor cards as `include_cards` and add
archetype-specific theme tags. The generator's existing include_cards path
then puts the anchor cards directly into the mainboard; corpus retrieval +
fallback fill the rest. This makes "build a modern burn deck" actually return
burn cards even when the corpus has no Burn shell.

Schema per entry:
  keywords:      lowercase substrings to search the brief for (order matters
                 — longer phrases first so "living end" beats "end").
  formats:       formats where this archetype is sensible. We only inject if
                 the request's format is in this list.
  colors:        canonical color identity for the archetype. Used to nudge
                 the request when the user left colors empty.
  playstyle_tags / theme_tags: merged into the request.
  anchor_cards:  list of (card_name, quantity). These get added to
                 include_cards. Quantity is a soft hint — the generator still
                 enforces deck-size limits.
  display_name:  shown in the deck title when this archetype is detected.

Keep each archetype list focused on truly canonical cards. The card pool /
corpus will fill flex slots — we are seeding the spine, not building the
whole deck.
"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class ManaBaseTemplate:
    """Per-archetype mana base recipe. Replaces hand-listed lands in
    anchor_cards with a structural recipe: total land count, ratio of
    utility/fetches/shocks, and any archetype-specific lands.

    The generator materializes this into actual land slots after the
    anchor cards are placed, picking the correct fetches/shocks for the
    archetype's colors. When None on a BuiltinArchetype, the generator
    falls back to its old hand-listed land logic.

    Fields:
      total_lands:     target count (e.g. 18 for Burn, 36 for Commander)
      shocks_ratio:    fraction of slots that should be shocklands (0-1)
      fetches_ratio:   fraction that should be fetchlands (0-1)
      utility_lands:   archetype-specific lands at fixed quantities
                       (e.g. Sunbaked Canyon × 4 for Burn, Sacred Foundry-
                       agnostic ones like Cavern of Souls × 4 for tribal)
      basics_min:      floor on basic land count (always >= this)
    """
    total_lands: int
    shocks_ratio: float = 0.0
    fetches_ratio: float = 0.0
    utility_lands: tuple[tuple[str, int], ...] = ()
    basics_min: int = 0


@dataclass(frozen=True)
class BuiltinArchetype:
    id: str
    display_name: str
    keywords: tuple[str, ...]
    formats: tuple[str, ...]
    colors: tuple[str, ...]
    playstyle_tags: tuple[str, ...]
    theme_tags: tuple[str, ...]
    anchor_cards: tuple[tuple[str, int], ...]
    strategy: str = ""
    # Per-archetype sideboard anchors. When set, the deck generator uses
    # these as the sideboard seed instead of the corpus role-pool grab bag.
    # Empty for archetypes that haven't been curated yet; the generator
    # falls back to the role-pool path. Aim for 12–15 cards covering the
    # archetype's standard matchups (e.g. Burn → graveyard hate, prison
    # hate, control hate).
    sideboard_anchors: tuple[tuple[str, int], ...] = ()
    # Mana-base template. When provided, the generator uses this recipe
    # instead of any hand-listed lands in anchor_cards (which can stay or
    # be removed — duplicates get deduped). None means "use anchor cards'
    # hand-listed lands as-is."
    mana_base: ManaBaseTemplate | None = None


