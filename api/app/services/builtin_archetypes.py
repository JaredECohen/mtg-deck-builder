# Tier-1 / meta-default archetype per format. Hit when the brief implies
# "give me a competitive deck" without naming a specific archetype — words
# like "best", "tier 1", "meta", "competitive", "tournament", "winning". The
# corpus is too thin and Standard-shaped to be a sane default here, so we
# pin a known top-tier archetype per format instead.
_META_DEFAULT_BY_FORMAT: dict[str, str] = {
    "modern": "modern-4c-omnath",
    "pioneer": "pioneer-mono-green-devotion",
    "standard": "standard-dimir-midrange",
    "legacy": "legacy-ur-delver",
    "commander": "commander-spellslinger",
}

_META_KEYWORDS = (
    "best possible",
    "best deck",
    "best modern",
    "best pioneer",
    "best standard",
    "best legacy",
    "best commander",
    "tier 1",
    "tier-1",
    "tier one",
    "meta deck",
    "the meta",
    "competitive",
    "tournament-grade",
    "tournament grade",
    "winning deck",
    "most competitive",
    "strongest deck",
    "top deck",
    "any color",
    "any colors",
    "any color(s)",
)


def _find_matching_keyword(archetype: BuiltinArchetype, lowered_prompt: str) -> str | None:
    """Return the first keyword from `archetype` that appears in the prompt,
    or None. Keywords are searched in declaration order, so more-specific
    phrases should come before broader ones inside each archetype.
    """
    for keyword in archetype.keywords:
        if keyword in lowered_prompt:
            return keyword
    return None


def detect_builtin_archetype(prompt: str, format_name: str) -> BuiltinArchetype | None:
    """Find the first built-in archetype whose keyword appears in the prompt.
    Kept for backward compatibility — single-archetype path.
    """
    matches = detect_builtin_archetypes(prompt, format_name)
    return matches[0] if matches else None


def detect_builtin_archetypes(prompt: str, format_name: str) -> list[BuiltinArchetype]:
    """Return ALL built-in archetypes whose keyword appears in the prompt
    AND whose `formats` list includes the requested format.

    To avoid noise from overlapping keywords (e.g. "burn" matching both
    mono-red burn and Boros burn), we apply a per-archetype suppression: if
    archetype A's matched keyword is a substring of archetype B's matched
    keyword AND A appears later in declaration order, A is dropped. In
    declaration order we put more-specific shells first, so this naturally
    keeps the most specific matches.

    A prompt like "burn + lifegain" matches two distinct archetypes and is
    returned in declaration order — callers can blend them.

    Meta-default fallback: if no archetype matched AND the brief reads like
    a generic "give me the best deck" request, we route to the tier-1
    archetype pinned for this format. Better than letting the deck generator
    hit the thin tournament corpus and produce a mono-W Lifegain pile.
    """
    if not prompt:
        return []
    lowered = prompt.lower()
    raw: list[tuple[BuiltinArchetype, str]] = []
    for archetype in BUILTIN_ARCHETYPES:
        if format_name not in archetype.formats:
            continue
        keyword = _find_matching_keyword(archetype, lowered)
        if keyword is not None:
            raw.append((archetype, keyword))

    if not raw and any(meta_kw in lowered for meta_kw in _META_KEYWORDS):
        default_id = _META_DEFAULT_BY_FORMAT.get(format_name)
        if default_id:
            for archetype in BUILTIN_ARCHETYPES:
                if archetype.id == default_id:
                    raw.append((archetype, "meta-default"))
                    break

    # Suppress later/broader matches whose keyword is fully contained in an
    # earlier/more-specific archetype's keyword. Example: if "mono-red burn"
    # matches the Mono-Red Burn archetype on keyword "mono-red burn", we
    # don't also report Boros Burn matching on "burn".
    kept: list[BuiltinArchetype] = []
    for i, (archetype_i, keyword_i) in enumerate(raw):
        suppressed = False
        for j, (_, keyword_j) in enumerate(raw):
            if i == j:
                continue
            if j < i and keyword_i in keyword_j and keyword_i != keyword_j:
                suppressed = True
                break
        if not suppressed:
            kept.append(archetype_i)
    return kept


def blend_archetypes(matches: list[BuiltinArchetype], format_name: str) -> BuiltinArchetype:
    """Merge multiple matched archetypes into a synthetic hybrid.

    Strategy:
      • display_name: "A + B" or "A + B + C" (capped at 3 for readability).
      • colors: ordered union (preserving WUBRG canonical order).
      • tags: union, deduped.
      • anchor_cards: take ~ceil(N / matches) cards from each archetype's
        anchor list (where N is the cap). Cards that appear in multiple
        archetypes win; their quantity is the max across matches. Result
        is capped at ~32 unique cards to leave fill room for the rest.
      • strategy: human-readable blend description.

    If only one match, returns it unchanged.
    """
    if len(matches) == 1:
        return matches[0]

    top = matches[:3]  # cap at 3-way blend
    name = " + ".join(m.display_name for m in top)
    keywords = tuple(dict.fromkeys(k for m in top for k in m.keywords))

    color_order = ["W", "U", "B", "R", "G", "C"]
    color_set = {c for m in top for c in m.colors}
    colors = tuple(c for c in color_order if c in color_set)

    playstyle = tuple(dict.fromkeys(t for m in top for t in m.playstyle_tags))
    themes = tuple(dict.fromkeys(t for m in top for t in m.theme_tags))

    # Per-archetype slice size — split the cap evenly so each contributes.
    CARD_CAP = 32
    per_archetype = max(8, CARD_CAP // len(top))

    # Track best quantity per card name across matches.
    card_qty: dict[str, int] = {}
    card_order: list[str] = []
    for m in top:
        for name_, qty in m.anchor_cards[:per_archetype]:
            if name_ not in card_qty:
                card_order.append(name_)
                card_qty[name_] = qty
            else:
                card_qty[name_] = max(card_qty[name_], qty)
    anchor_cards = tuple((n, card_qty[n]) for n in card_order)

    strategy = (
        f"Hybrid blending {', '.join(m.display_name for m in top)}. "
        f"Anchor cards seeded from each archetype's core; the rest filled "
        f"from the {format_name} card pool."
    )

    return BuiltinArchetype(
        id="blend-" + "-".join(m.id for m in top),
        display_name=name,
        keywords=keywords,
        formats=tuple(set.intersection(*(set(m.formats) for m in top))) or (format_name,),
        colors=colors,
        playstyle_tags=playstyle,
        theme_tags=themes,
        anchor_cards=anchor_cards,
        strategy=strategy,
    )
